def _move_before_first_plate(topic_id: str, text_prefix: str) -> None:
    """Move a paragraph above the first plate so the plate starts a page
    together with the text instead of leaving a half-empty page behind."""
    for t in TOPICS:
        if t["topic_id"] != topic_id:
            continue
        blocks = t["blocks"]
        src = next(b for b in blocks
                   if b["type"] == "p" and text_prefix in b["text"])
        dst = next(b for b in blocks if b["type"] == "plate")
        blocks.remove(src)
        blocks.insert(blocks.index(dst), src)


