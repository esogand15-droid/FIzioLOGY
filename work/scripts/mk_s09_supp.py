def patch_outline() -> None:
    outline = json.loads(OUT_OUTLINE.read_text(encoding="utf-8"))
    keep = [t for t in outline["topics"] if not t.get("supp")]
    keep.extend({k: v for k, v in t.items() if k != "blocks"} for t in TOPICS)
    outline["topics"] = keep
    outline["supp_note"] = (
        "ده نکتهٔ تکمیلی این جلسه از دو جزوهٔ دکتر قدیری (مخچه، ۱۰ صفحه؛ عقده‌های قاعده‌ای، "
        "۲۰ صفحه — مهر ۱۴۰۳) آمده‌اند؛ هر دو جزوه کامل مصرف شده‌اند.")
    OUT_OUTLINE.write_text(json.dumps(outline, ensure_ascii=False, indent=1) + "\n",
                           encoding="utf-8")


def main() -> int:
    OUT_CONTENT.write_text(json.dumps(TOPICS, ensure_ascii=False, indent=1) + "\n",
                           encoding="utf-8")
    patch_outline()
    p1 = {x for t in TOPICS for x in t["supp"]["pages"] if t["supp"]["short"].endswith("مخچه")}
    p2 = {x for t in TOPICS for x in t["supp"]["pages"] if t["supp"]["short"].endswith("عقده")}
    print(f"supplement topics {len(TOPICS)} | B1 pages {len(p1)} | B2 pages {len(p2)}")
    print("unused B1:", [i for i in range(2, 11) if i not in p1])
    print("unused B2:", [i for i in range(2, 21) if i not in p2])
    print("->", OUT_CONTENT.name, "|", OUT_OUTLINE.name)
    return 0


