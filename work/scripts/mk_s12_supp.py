def patch_outline() -> None:
    outline = json.loads(OUT_OUTLINE.read_text(encoding="utf-8"))
    keep = [t for t in outline["topics"] if not t.get("supp")]
    keep.extend({k: v for k, v in t.items() if k != "blocks"} for t in TOPICS)
    outline["topics"] = keep
    outline["supp_note"] = (
        "هفت نکتهٔ تکمیلی این جلسه از جزوهٔ «فعالیت‌های مغزی — دکتر قدیری» (مهر ۱۴۰۳) "
        "آمده‌اند؛ جدول عددی امواج، آزمون قطع تالاموس، سازوکار کلسیمی تشنج، صحنه‌های بالینی "
        "صرع غیاب و مراکز خواب با میانجی‌هایشان در جزوهٔ رسمی به این تفصیل نیامده است.")
    OUT_OUTLINE.write_text(json.dumps(outline, ensure_ascii=False, indent=1) + "\n",
                           encoding="utf-8")


