def plate(book, asset, title, citation, en, view, fa, labels, max_h=106):
    return dict(type="plate", book=book, asset=f"images_anatomy/{asset}.jpeg",
                title=title, citation=citation, en_caption=en, view=view,
                fa_text=fa, labels=labels, src=citation, max_h=max_h)


def p(text, src):
    return dict(type="p", text=text, src=src)


def ul(items, src):
    return dict(type="ul", items=items, src=src)


def table(head, rows, widths, caption, src):
    return dict(type="table", head=head, rows=rows, widths=widths,
                caption=caption, src=src)


def callout(kind, title, text, src):
    return dict(type="callout", kind=kind, title=title, text=text, src=src)


def handoff(title, kicker, sources, checklist, open_, question):
    return dict(type="handoff", title=title, kicker=kicker, sources=sources,
                checklist=checklist, open=open_, question=question)


