def patch_outline() -> None:
    outline = json.loads(OUT_OUTLINE.read_text(encoding="utf-8"))
    keep = [t for t in outline["topics"] if not t.get("supp")]
    keep.extend({k: v for k, v in t.items() if k != "blocks"} for t in TOPICS)
    outline["topics"] = keep
    outline["supp_note"] = (
        "شش نکتهٔ تکمیلی این جلسه از جزوهٔ «دکتر قدیری — جلسهٔ آخر» (مهر ۱۴۰۳) آمده‌اند؛ "
        "جزوهٔ رسمی این جلسه در صفحه‌های ۵ تا ۱۴ دربارهٔ حافظه ساکت است و صفحه‌های ۱۳ تا ۱۷ "
        "آن به تکلم می‌پردازد.")
    OUT_OUTLINE.write_text(json.dumps(outline, ensure_ascii=False, indent=1) + "\n",
                           encoding="utf-8")


def main() -> int:
    OUT_CONTENT.write_text(json.dumps(TOPICS, ensure_ascii=False, indent=1) + "\n",
                           encoding="utf-8")
    patch_outline()
    pages = sorted({p for t in TOPICS for p in t["supp"]["pages"]})
    print(f"supplement topics {len(TOPICS)} | pages {pages[0]}-{pages[-1]} ({len(pages)})")
    print("unused pages of the booklet:", [p for p in range(2, 18) if p not in pages])
    print("->", OUT_CONTENT.name, "|", OUT_OUTLINE.name)
    return 0


