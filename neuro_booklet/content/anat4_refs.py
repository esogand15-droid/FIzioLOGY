def FIG(path, cap, src):
    """نسبت عرض و بیشترین ارتفاع را از خود فایل می‌خواند."""
    from PIL import Image
    w, h = Image.open(path).size
    ratio = 0.86 if w >= h else 0.62
    maxh = 74 if w >= h else 64
    if h > w * 1.15:
        ratio, maxh = 0.52, 62
    return ("fig", path, cap, src, ratio, maxh)

