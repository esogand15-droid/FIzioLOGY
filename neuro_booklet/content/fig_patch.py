def apply_extra(groups):
    """groups: list of mabhas-lists؛ درج بر اساس شمارهٔ مبحث."""
    index = {}
    for group in groups:
        for blocks in group:
            if blocks and blocks[0][0] == "mabhas":
                index[blocks[0][1]] = blocks
    for table in (EXTRA_A, EXTRA_B):
        for no, inserts in table.items():
            blocks = index.get(no)
            if blocks is None:
                raise KeyError(f"مبحث {no} پیدا نشد")
            for pos, new_blocks in sorted(inserts, key=lambda x: -x[0]):
                for off, blk in enumerate(new_blocks):
                    blocks.insert(pos + off, blk)
    return groups
