"""محتوا‌ی جلسهٔ ۲ — نسخهٔ بازنویسی‌شده به‌صورت جزوهٔ مادر.

قاعدهٔ این فایل همان قاعدهٔ جلسهٔ ۱ است
--------------------------------------
۱) هیچ جمله‌ای دربارهٔ جزوه نوشته نمی‌شود؛ خودِ محتوا نوشته می‌شود.
۲) هر شکل، بی‌درنگ پس از پاراگرافی می‌آید که آن را توضیح می‌دهد.
۳) هر مبحث یک شناسنامه، متن ساخت‌یافته و یک برگهٔ تحویل دارد.
۴) هر بلوک متنی ارجاع صفحه دارد.

    .venv/bin/python headneck/scripts/hn02_build_content.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "headneck" / "content"
IMG = "headneck/images"

_docs: dict[str, list] = {"a": [], "b": []}

_FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa(s):  # ارقام فارسی، همان قاعدهٔ جلسهٔ ۱
    return str(s).translate(_FA)


# ─────────────────────────────────────────────────────────── سازندهٔ بلوک‌ها
def p(text, src):
    return dict(type="p", text=text, src=src)


def ul(items, src):
    return dict(type="ul", items=items, src=src)


def ol(items, src):
    return dict(type="ol", items=items, src=src)


def h3(text):
    return dict(type="h3", text=text)


def table(head, rows, caption, src, widths=None):
    blk = dict(type="table", head=head, rows=rows, caption=caption, src=src)
    if widths:
        blk["widths"] = widths
    return blk


def callout(title, text, src, kind="key"):
    return dict(type="callout", kind=kind, title=title, text=text, src=src)


def lec(asset, page, title, view, fa_, labels, src_extra="", max_h=None):
    blk = dict(type="plate", book="lecture", asset=f"{IMG}/{asset}.jpeg",
               title=title, citation=f"جزوهٔ درس، ص {page}", view=view,
               fa_text=fa_, labels=labels,
               src=f"جزوهٔ درس، ص {page}" + (f" · {src_extra}" if src_extra else ""))
    if max_h:
        blk["max_h"] = max_h
    return blk


def netter(plate, title, en, view, fa_, labels, src_extra="", max_h=132):
    return dict(type="plate", book="netter",
                asset=f"{IMG}/hn02_netter_p{plate}.jpeg", title=title,
                citation=f"نتر، ویراست ۸، پلیت {fa(plate)}، ص {fa(plate + 52)}",
                en_caption=en, view=view, fa_text=fa_, labels=labels, max_h=max_h,
                src=f"نتر، پلیت {plate}" + (f" · {src_extra}" if src_extra else ""))


def grays(fig, page, asset, title, en, view, fa_, labels, body=""):
    return dict(type="plate", book="grays", asset=f"{IMG}/{asset}.jpeg",
                title=title, citation=f"گری، شکل {fa(fig)}، ص {fa(page)}",
                en_caption=en, view=view, fa_text=fa_, labels=labels,
                en_body=body, src=f"گری، شکل {fa(fig)}، ص {fa(page)}", max_h=126)


def idcard(rows, footer, kicker="قبل از شروع این مبحث بخوانید"):
    return dict(type="idcard", title="شناسنامهٔ مبحث", kicker=kicker,
                rows=rows, footer=footer)


def handoff(title, sources, open_, question):
    return dict(type="handoff", title=title,
                kicker="این برگه را نویسندهٔ مبحث پر می‌کند",
                sources=sources,
                checklist=[
                    "همهٔ سطرهای این مبحث با ارجاع صفحه نوشته شد.",
                    "هر شکل درست پس از پاراگراف مرتبط خودش نشسته است.",
                    "هیچ جمله یا عددی از منبع جا نیفتاده است.",
                    "اصطلاح‌های انگلیسی یک‌دست و با املای واحد نوشته شد.",
                    "مبحث یک‌بار در نسخهٔ چاپی خوانده و غلط تایپی اصلاح شد.",
                ],
                open=open_, question=question)


def topic(tid, blocks, doc):
    _docs[doc].append(dict(topic_id=tid, blocks=blocks))


