def apply_max_h() -> None:
    for topics in _docs.values():
        for t in topics:
            for b in t["blocks"]:
                if b.get("type") != "plate":
                    continue
                key = b["asset"].rsplit("/", 1)[-1][:-5]
                if key in MAX_H:
                    b["max_h"] = MAX_H[key]


def main() -> int:
    apply_max_h()
    for key, fname in (("a", "hn02_a.json"), ("b", "hn02_b.json")):
        path = OUT / fname
        path.write_text(json.dumps(_docs[key], ensure_ascii=False, indent=1) + "\n",
                        encoding="utf-8")
        n_blocks = sum(len(t["blocks"]) for t in _docs[key])
        n_plates = sum(1 for t in _docs[key] for b in t["blocks"]
                       if b.get("type") == "plate")
        print(f"{fname}: {len(_docs[key])} topics · {n_blocks} blocks · {n_plates} plates")
    return 0


