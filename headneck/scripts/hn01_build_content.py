# ─────────────────────────────────────────────────────────── سازندهٔ بلوک‌ها
_docs: dict[str, list] = {"a": [], "b": []}


def p(text, src, doc="a"):
    return dict(type="p", text=text, src=src)


def ul(items, src):
    return dict(type="ul", items=items, src=src)


def ol(items, src):
    return dict(type="ol", items=items, src=src)


def h3(text):
    return dict(type="h3", text=text)


def table(head, rows, caption, src):
    return dict(type="table", head=head, rows=rows, caption=caption, src=src)


def callout(title, text, src, kind="key"):
    return dict(type="callout", kind=kind, title=title, text=text, src=src)


def lec(asset, page, title, view, fa, labels, src_extra="", max_h=None):
    blk = dict(type="plate", book="lecture", asset=f"{IMG}/{asset}.jpeg",
                title=title, citation=f"جزوهٔ درس، ص {page}", view=view,
                fa_text=fa, labels=labels,
                src=f"جزوهٔ درس، ص {page}" + (f" · {src_extra}" if src_extra else ""))
    if max_h:
        blk["max_h"] = max_h
    return blk


def netter(plate, pdf_page, title, en, view, fa, labels, src_extra=""):
    return dict(type="plate", book="netter",
                asset=f"{IMG}/hn01_netter_p{plate}.jpeg", title=title,
                citation=f"نتر، ویراست ۸، پلیت {plate}، ص {pdf_page}",
                en_caption=en, view=view, fa_text=fa, labels=labels,
                src=f"نتر، پلیت {plate}" + (f" · {src_extra}" if src_extra else ""))


def grays(fig, page, asset, title, en, view, fa, labels, body=""):
    return dict(type="plate", book="grays", asset=f"{IMG}/{asset}.jpeg",
                title=title, citation=f"گری، شکل {fig}، ص {page}",
                en_caption=en, view=view, fa_text=fa, labels=labels,
                en_body=body, src=f"گری، شکل {fig}، ص {page}")


def idcard(rows, footer, kicker="قبل از شروع این مبحث بخوانید"):
    return dict(type="idcard", title="شناسنامهٔ مبحث", kicker=kicker,
                rows=rows, footer=footer)


def handoff(title, sources, open_, question):
    return dict(type="handoff", title=title,
                kicker="این برگه را نویسندهٔ مبحث پر می‌کند",
                sources=sources,
                checklist=[
                    "همهٔ سطرهای این مبحث با ارجاع صفحه نوشته شد.",
                    "هر شکل درست پس از پاراگراف مرتبط خودش نشسته است.",
                    "هیچ جمله یا عددی از منبع جا نیفتاده است.",
                    "اصطلاح‌های انگلیسی یک‌دست و با املای واحد نوشته شد.",
                    "مبحث یک‌بار در نسخهٔ چاپی خوانده و غلط تایپی اصلاح شد.",
                ],
                open=open_, question=question)


def topic(tid, blocks, doc):
    _docs[doc].append(dict(topic_id=tid, blocks=blocks))


