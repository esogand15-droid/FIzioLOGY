def conflict_cards(paras_in_section):
    """تفاوت عددی میان دو منبع مختلف در همان زیرمبحث → کارت نیازمند بررسی."""
    cards = []
    by_src = {}
    for p in paras_in_section:
        by_src.setdefault(p["sid"], []).append(p)
    if len(by_src) < 2:
        return cards
    srcs = list(by_src)[:4]
    for i in range(len(srcs)):
        for j in range(i + 1, len(srcs)):
            for a in by_src[srcs[i]]:
                for b in by_src[srcs[j]]:
                    na, nb = NUM.findall(a["text"]), NUM.findall(b["text"])
                    if not na or not nb or na == nb:
                        continue
                    wa, wb = norm_words(a["text"]), norm_words(b["text"])
                    common = wa & wb
                    if len(common) >= 6 and (set(na) ^ set(nb)):
                        cards.append({
                            "type": "source_conflict",
                            "title": "تفاوت عددی میان منابع (نیازمند بررسی)",
                            "description": "در دو منبع، جمله‌هایی با موضوع مشترک اما اعداد متفاوت دیده شد؛ "
                                           "هیچ‌کدام خودسرانه ترجیح داده نشده است.",
                            "items": [
                                {"source": a["sid"], "page": a.get("page"), "text": a["text"][:400],
                                 "numbers": na[:6]},
                                {"source": b["sid"], "page": b.get("page"), "text": b["text"][:400],
                                 "numbers": nb[:6]},
                            ],
                            "status": "بررسی‌نشده",
                        })
                        if len(cards) >= 1:
                            return cards
    return cards


DEDUPE = {}


def build():
    manifest = []
    for ch in CHAPTERS:
        sections = []
        paras = []
        for b in ch["bodies"]:
            items = body_paragraphs(b["sid"])
            if b.get("filter"):
                items = [p for p in items if re.search(b["filter"], p["text"])]
            else:
                items = slice_by(items, b.get("start"), b.get("end"))
            for it in items:
                it["role"] = "body"
            paras += items
        for b in ch.get("supplements", []):
            items = body_paragraphs(b["sid"])
            items = slice_by(items, b.get("start"), b.get("end"))
            for it in items:
                it["role"] = "supplement"
                it["label"] = b["label"]
            paras += items

        # حذف پاراگراف‌های بی‌محتوا (فقط نقطه/فاصله/نشانه)
        paras = [p for p in paras
                 if len(re.findall(r"[\w\u0600-\u06FF]", p["text"])) >= 15]
        paras, dropped = dedupe_paras(paras)
        if dropped:
            DEDUPE[ch["id"]] = dropped
        grouped = assign_sections(paras, ch["sections"])
        figs = figures_for({b["sid"] for b in ch["bodies"]} | {b["sid"] for b in ch.get("supplements", [])})
        used_figs = set()

        for si, sec in enumerate(ch["sections"], start=1):
            sid = f"{ch['id']}-S{si:02d}"
            blocks = [{"type": "heading", "level": 2, "text": sec["title"]}]
            sec_paras = grouped[si - 1]
            sec_paras.sort(key=lambda p: p["i"])
            total_chars = sum(len(p["text"]) for p in sec_paras)
            if not sec_paras:
                blocks.append({"type": "callout", "kind": "needs_review",
                               "title": "نیازمند بررسی",
                               "text": "برای این زیرمبحث، متن قابل‌استفاده‌ای در منابع استخراج‌شده یافت نشد. "
                                       "منابع مرتبط (در صورت وجود) در پیوست همین فصل آمده است."})
            last_src = None
            for p in sec_paras:
                if p["role"] == "supplement":
                    blocks.append({"type": "supplement", "source_type": p["label"],
                                   "text": p["text"],
                                   "sources": [{"sid": p["sid"], "page": p.get("page")}]})
                    last_src = None
                else:
                    blocks.append({"type": "paragraph", "text": p["text"],
                                   "sources": [{"sid": p["sid"], "page": p.get("page")}]})
                    last_src = p["sid"]
            # شکل‌ها: صفحه‌های این زیرمبحث
            pages = {(fig_source(p["sid"]), p.get("page")) for p in sec_paras}
            for key in sorted(pages, key=lambda k: (k[0], k[1] or 0)):
                for f in figs.get(key, [])[:2]:
                    if f["figure_id"] in used_figs:
                        continue
                    used_figs.add(f["figure_id"])
                    blocks.append({"type": "figure", "figure_id": f["figure_id"],
                                   "file": f["file"], "caption": "",
                                   "sources": [{"sid": f["source_id"], "page": f["page"]}]})
            for c in conflict_cards(sec_paras):
                blocks.append(c)
            size = "small" if total_chars < 2500 else ("large" if total_chars > 9000 else "medium")
            blocks.append({"type": "team_notes", "size": size})
            sections.append({
                "section_id": sid, "title": sec["title"],
                "prerequisites": ch["prereq"],
                "chars": total_chars,
                "blocks": blocks,
            })
        appendices = [APX[sid] for sid in [a["sid"] for a in ch.get("appendix", [])] if sid in APX]
        data = {"chapter_id": ch["id"], "chapter_title": ch["title"], "scope": ch["scope"],
                "sections": sections,
                "notes": ch.get("notes", []),
                "_bodies": ch["bodies"],
                "sources": [b["sid"] for b in ch["bodies"]] +
                           [b["sid"] for b in ch.get("supplements", [])],
                "appendix": appendices}
        json.dump(data, open(os.path.join(LOCK, ch["id"] + ".json"), "w"), ensure_ascii=False, indent=1)
        n_par = sum(1 for s in sections for b in s["blocks"] if b["type"] in ("paragraph", "supplement"))
        n_fig = sum(1 for s in sections for b in s["blocks"] if b["type"] == "figure")
        manifest.append({"chapter_id": ch["id"], "title": ch["title"], "sections": len(sections),
                         "paragraphs": n_par, "figures": n_fig,
                         "chars": sum(s["chars"] for s in sections)})
        print(f"{ch['id']} sections={len(sections)} paras={n_par} figs={n_fig} "
              f"chars={manifest[-1]['chars']} unused_figs={len(figs)-len(used_figs)}")
    json.dump(manifest, open(os.path.join(ROOT, "lock", "manifest.json"), "w"), ensure_ascii=False, indent=1)
    json.dump(DEDUPE, open(os.path.join(WORK, "dedupe_log.json"), "w"), ensure_ascii=False, indent=1)
    print("پاراگراف‌های تکراری حذف‌شده:", sum(len(v) for v in DEDUPE.values()))


if __name__ == "__main__":
    build()
