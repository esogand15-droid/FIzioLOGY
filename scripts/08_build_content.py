import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = os.path.join(ROOT, "work")
LOCK = os.path.join(ROOT, "lock", "chapters")
os.makedirs(LOCK, exist_ok=True)

CHA = json.load(open(os.path.join(WORK, "pages_map.json")))
REG = {r["source_id"]: r for r in json.load(open(os.path.join(WORK, "source_registry.json")))}
FIG = json.load(open(os.path.join(ROOT, "images", "INDEX.json")))
APX = json.load(open(os.path.join(WORK, "appendix_pages.json")))

NUM = re.compile(r"[۰-۹0-9][۰-۹0-9.,/]*")


def load_flow(sid):
    p = os.path.join(WORK, "flows_norm", sid + ".json")
    return json.load(open(p))


def body_paragraphs(sid):
    """پاراگراف‌های یک منبع با شماره صفحه."""
    d = load_flow(sid)
    paras = d["paragraphs"]
    if not d.get("normalized"):
        return []
    if sid in CHA:
        pages = CHA[sid]["pages"]
        return [{"sid": sid, "page": pages[i] if i < len(pages) else None,
                 "text": p["text"], "i": i} for i, p in enumerate(paras)]
    return [{"sid": sid, "page": p.get("page"), "text": p["text"], "i": i}
            for i, p in enumerate(paras)]


def slice_by(paras, start=None, end=None):
    s = 0
    e = len(paras)
    if start:
        for i, p in enumerate(paras):
            if re.search(start, p["text"]):
                s = i
                break
    if end:
        for i in range(s, len(paras)):
            if re.search(end, paras[i]["text"]):
                e = i
                break
    return paras[s:e]


