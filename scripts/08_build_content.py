def norm_words(t):
    return set(re.findall(r"[\w\u0600-\u06FF\u200c]{3,}", t))


def assign_sections(paras, sections):
    """انتساب هر پاراگراف به زیرمبحث بر پایه امتیاز وزنی کلیدواژه‌ها.

    وزن هر کلیدواژه = (طول کلیدواژه) × (۱ / تعداد زیرمبحث‌هایی که آن را دارند)
    تا کلیدواژه‌های اختصاصی بر کلیدواژه‌های عمومی (مثل «رفلکس») اولویت بگیرند.
    """
    df = {}
    for sec in sections:
        for k in set(sec["kw"]):
            df[k] = df.get(k, 0) + 1
    weights = {k: (len(k) / 6.0) * (1.0 / df[k]) for k in df}
    out = [[] for _ in sections]
    cur = None
    for p in paras:
        t = p["text"]
        scores = []
        for sec in sections:
            sc = 0.0
            for k in sec["kw"]:
                c = t.count(k)
                if c:
                    sc += min(c, 4) * weights[k]
            scores.append(sc)
        best = max(range(len(sections)), key=lambda i: scores[i])
        if scores[best] <= 0:
            best = cur if cur is not None else 0
        elif cur is not None and scores[cur] > 0 and abs(scores[best] - scores[cur]) < 0.35:
            best = cur          # در حالت نزدیک، پیوستگی حفظ می‌شود
        cur = best
        out[best].append(p)
    return out


def dedupe_paras(paras):
    """حذف پاراگراف‌های تکراری (منابع با محتوای یکسان یا متن تکراری بین نقش‌ها)."""
    import difflib
    kept, dropped = [], []
    for p in paras:
        dup = None
        for q in kept:
            if abs(len(p["text"]) - len(q["text"])) > max(len(p["text"]), len(q["text"])) * 0.35:
                continue
            sm = difflib.SequenceMatcher(None, p["text"][:400], q["text"][:400])
            if sm.quick_ratio() < 0.90:
                continue
            if sm.ratio() >= 0.93:
                dup = q
                break
        if dup is None:
            kept.append(p)
        else:
            dropped.append({"source_id": p["sid"], "duplicate_of": dup["sid"],
                            "role": p["role"], "text": p["text"][:120]})
    return kept, dropped


